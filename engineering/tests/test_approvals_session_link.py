LINK = "https://claude.ai/code/session_01AbCdEf"
FOOTER = f"_Generated by [Claude Code]({LINK})_"
# a body land accepts: it has an Evidence section with content
BODY = "## Summary\n\nFix it.\n\n## Evidence\n\nlog line"


def test_unlinked_drops_a_bare_session_link_line_and_folds_its_blank_lines() -> None:
    """A bare link line, one in <...>, or the proxy's footer goes and its blank lines fold as a `Claude-Session:`
    line's do."""
    for line in (LINK, f"<{LINK}>", f"{LINK}  ", FOOTER):
        assert approvals.unlinked(f"## Summary\n\nFix it.\n\n{line}\n") == "## Summary\n\nFix it."
        assert approvals.unlinked(f"a\n{line}\nb") == "a\nb"
        assert approvals.unlinked(f"a\n\n{line}\n\nb") == "a\n\nb"
    # a line that only mentions such a link inside other text stays
    for kept in (
        f"See {LINK} for the run.",
        f"- {LINK}",
        f"[run]({LINK})",
        f"{LINK} ran it",
        f"{FOOTER} and more",
        "_Generated by [Claude Code](https://example.com/code/session_01AbCdEf)_",
        "https://example.com/code/session_01AbCdEf",
    ):
        assert approvals.unlinked(f"a\n\n{kept}\n") == f"a\n\n{kept}"


def test_land_body_under_pr_body_returns_the_body_without_the_link_line(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    monkeypatch.setattr(
        approvals,
        "gh",
        lambda *args: (
            '{"squash_merge_commit_message": "PR_BODY"}'
            if args == ("api", "repos/{owner}/{repo}")
            else ""
        ),
    )
    body = f"## Summary\n\nFix it.\n\n## Evidence\n\nlog line\n\n{LINK}\n"
    assert approvals.land_body({"number": 7, "body": body}) == (
        "## Summary\n\nFix it.\n\n## Evidence\n\nlog line"
    )


def editable(found: dict[str, Any], **fields: Any) -> dict[str, Any]:
    """A PR body or comment as GraphQL reads it for an account that may edit it."""
    return {**found, "viewerCanUpdate": True, **fields}


def test_land_edits_a_pr_body_that_carries_the_link_and_leaves_a_clean_one_untouched(
    lands: dict[str, Any], hub: dict[str, list[dict[str, Any]]]
) -> None:
    lands["open"](7, {"7.txt": "7\n"}, body=f"{BODY}\n\n{LINK}\n")
    lands["open"](8, {"8.txt": "8\n"}, body=f"{BODY}\n")
    for number in (7, 8):
        lands["pulls"][number]["viewerCanUpdate"] = True
    code, lines = lands["land"]()
    assert code == 0, lines
    assert lands["edits"] == {"repos/{owner}/{repo}/pulls/7": BODY}
    assert "PR #7: dropped the session link from its body" in lines
    assert not any(line.startswith("PR #8: dropped") for line in lines)
    assert sorted(lands["merged"]()) == ["7", "8"]
    # the body is edited before its PR merges
    calls = [args[:4] for args in lands["calls"]]
    edit = calls.index(("api", "-X", "PATCH", "repos/{owner}/{repo}/pulls/7"))
    assert edit < [args[:3] for args in calls].index(("pr", "merge", "7"))


def test_land_edits_a_comment_carrying_the_link_or_the_footer_keeping_its_other_lines(
    lands: dict[str, Any], hub: dict[str, list[dict[str, Any]]]
) -> None:
    """A conversation comment with the bare link and a review comment with the proxy's footer each get one edit that
    keeps their other lines; a clean comment and one this account can't edit get none."""
    linked = editable(
        note(f"Verdict: pass\n\nAll green.\n\n{LINK}"), databaseId=11, url="https://example.com/c11"
    )
    clean = editable(note("No link here."), databaseId=12, url="https://example.com/c12")
    theirs = note(
        f"From another account.\n\n{FOOTER}", databaseId=13, url="https://example.com/c13"
    )
    lands["open"](7, {"7.txt": "7\n"}, comments=(linked, clean, theirs))
    review = editable(
        {"body": f"Rename this.\n\n{FOOTER}\n"}, databaseId=21, url="https://example.com/r21"
    )
    lands["pulls"][7]["reviewThreads"] = {
        "totalCount": 1,
        "nodes": [{"isResolved": True, "comments": {"nodes": [review]}}],
    }
    code, lines = lands["land"]()
    assert code == 0, lines
    assert lands["edits"] == {
        "repos/{owner}/{repo}/issues/comments/11": "Verdict: pass\n\nAll green.",
        "repos/{owner}/{repo}/pulls/comments/21": "Rename this.",
    }
    assert (
        "PR #7: dropped the session link from the comment https://example.com/c11, the comment"
        " https://example.com/r21"
    ) in lines
    assert lands["merged"]() == ["7"]


def test_check_merge_names_a_comment_carrying_a_link_it_cannot_edit(
    monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    theirs = note(
        f"From another account.\n\n{FOOTER}", databaseId=13, url="https://example.com/c13"
    )
    mine = editable(note(f"Mine.\n\n{LINK}"), databaseId=14, url="https://example.com/c14")
    pr = pull(comments=(theirs, mine))
    monkeypatch.setattr(approvals, "pull_request", lambda _n: pr)
    monkeypatch.setattr(approvals, "project", lambda: (None, LOOP))
    code = approvals.main(["check", "merge", "7"])
    out = capsys.readouterr().out.splitlines()
    named = [line for line in out if "a session link stays in" in line]
    assert named == [
        (
            "PR #7: a session link stays in the comment https://example.com/c13, which this account can't edit:"
            " remove it by hand before the PR lands, since its page is public"
        )
    ]
    # the line is advice: the same PR without the link exits the same way and names nothing
    pr["comments"]["nodes"][:] = [editable(note("Clean."), databaseId=15)]
    assert approvals.main(["check", "merge", "7"]) == code
    assert "a session link stays in" not in capsys.readouterr().out


def test_land_edits_a_review_summary_carrying_the_link_and_check_merge_names_one_it_cannot_edit(
    lands: dict[str, Any],
    hub: dict[str, list[dict[str, Any]]],
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    """A review's summary is a text of the PR as its comments are: one this account can edit gets one PUT keeping its
    other lines, and check merge names one it can't."""
    summary = {"author": {"login": "loop"}, "state": "COMMENTED", "commit": {"oid": "0" * 40}}
    mine = editable(
        {**summary, "body": f"Verifier, pass 1.\n\nVERDICT: 0 blocker\n\n{FOOTER}"},
        databaseId=31,
        url="https://example.com/v31",
    )
    lands["open"](7, {"7.txt": "7\n"})
    # older than the verdict on the head, which stays the newest review
    lands["pulls"][7]["reviews"]["nodes"].insert(0, mine)
    code, lines = lands["land"]()
    assert code == 0, lines
    assert lands["edits"] == {
        "repos/{owner}/{repo}/pulls/7/reviews/31": "Verifier, pass 1.\n\nVERDICT: 0 blocker"
    }
    edits = [args[:4] for args in lands["calls"] if args[:2] == ("api", "-X")]
    assert edits == [("api", "-X", "PUT", "repos/{owner}/{repo}/pulls/7/reviews/31")]
    assert "PR #7: dropped the session link from the review https://example.com/v31" in lines
    theirs = {
        **summary,
        "body": f"Looks fine.\n\n{LINK}",
        "databaseId": 32,
        "url": "https://example.com/v32",
    }
    pr = pull(reviews=(theirs,))
    monkeypatch.setattr(approvals, "pull_request", lambda _n: pr)
    monkeypatch.setattr(approvals, "project", lambda: (None, LOOP))
    approvals.main(["check", "merge", "7"])
    assert [
        line for line in capsys.readouterr().out.splitlines() if "a session link stays in" in line
    ] == [
        (
            "PR #7: a session link stays in the review https://example.com/v32, which this account can't edit: remove"
            " it by hand before the PR lands, since its page is public"
        )
    ]


def test_over_rest_every_linked_text_is_named_by_its_url_and_none_is_edited(
    cloud: Cloud, capsys: pytest.CaptureFixture[str]
) -> None:
    """Where GraphQL is refused, REST still reads each text's id and link, and a review thread's comments by the ids
    its route names; with no right to edit any read there, land edits none and check merge names each one."""
    pages = cloud.routes
    pages["repos/{owner}/{repo}/issues/7/comments?per_page=100"] = [
        rest_comment(f"Pass.\n\n{LINK}", id=41, html_url="https://example.com/c41")
    ]
    pages["repos/{owner}/{repo}/pulls/7/comments?per_page=100"] = [
        {"id": 1, "body": f"Rename this.\n\n{FOOTER}", "html_url": "https://example.com/r1"}
    ]
    pages["repos/{owner}/{repo}/pulls/7/reviews?per_page=100"][0].update(
        id=51, html_url="https://example.com/v51", body=f"Verifier.\n\n{FOOTER}"
    )
    pr = approvals.pull_request(7)
    approvals.unlink_pull(pr)
    assert cloud.writes == []
    assert approvals.stranded(pr) == (
        "PR #7: a session link stays in the comment https://example.com/c41, the review https://example.com/v51,"
        " the comment https://example.com/r1, which this account can't edit: remove it by hand before the PR lands,"
        " since its page is public"
    )
    capsys.readouterr()


def selection(query: str) -> dict[str, Any]:
    """The fields a GraphQL query selects, as {its key in the answer (an alias, else the field): what it selects
    under it, or None for a leaf}; arguments are dropped and an inline fragment's fields merge into its parent's."""
    while re.search(r"\([^()]*\)", query):
        query = re.sub(r"\([^()]*\)", "", query)
    tokens = re.findall(r"\.\.\.|\w+|[{}:]", query)

    def fields(at: int) -> tuple[dict[str, Any], int]:
        found: dict[str, Any] = {}
        while tokens[at] != "}":
            if tokens[at] == "...":
                under, at = fields(at + 4)  # `... on Type {`
                found.update(under)
                continue
            key, at = tokens[at], at + 1
            if tokens[at] == ":":
                at += 2  # `alias: field`, answered under the alias
            under = None
            if tokens[at] == "{":
                under, at = fields(at + 1)
            found[key] = under
        return found, at + 1

    return fields(tokens.index("{") + 1)[0]


def answered(data: Any, selected: dict[str, Any] | None) -> Any:
    """data as GitHub would answer the selection: only the fields it names, at every depth."""
    if selected is None or data is None:
        return data
    if isinstance(data, list):
        return [answered(each, selected) for each in data]
    return {key: answered(data[key], under) for key, under in selected.items() if key in data}


def test_the_pr_query_reads_each_texts_link_id_and_right_to_edit(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Through pull_request()'s own GraphQL query, answered with only the fields it names: the body's, each
    conversation comment's, each review's and each thread comment's text, id, link and right to edit all come back,
    so session_links() finds every one as editable."""
    link = f"Text.\n\n{LINK}"
    found = pull(
        body=link, comments=(editable(note(link), databaseId=11, url="https://example.com/c11"),)
    )
    found["viewerCanUpdate"] = True
    found["reviews"]["nodes"] = [
        editable(
            {
                "author": {"login": "loop"},
                "state": "COMMENTED",
                "body": link,
                "commit": {"oid": HEAD},
            },
            databaseId=31,
            url="https://example.com/v31",
        )
    ]
    found["reviewThreads"] = {
        "totalCount": 1,
        "nodes": [
            {
                "isResolved": True,
                "comments": {
                    "nodes": [
                        editable({"body": link}, databaseId=21, url="https://example.com/r21")
                    ]
                },
            }
        ],
    }
    queries = []

    def gh(*args: str, data: str | None = None) -> str:
        query = next(arg for arg in args if arg.startswith("query="))
        queries.append(query)
        return json.dumps(
            {"data": answered({"repository": {"pullRequest": found}}, selection(query[6:]))}
        )

    monkeypatch.setattr(approvals, "gh", gh)
    monkeypatch.setattr(approvals, "_rest_only", False)
    texts = approvals.session_links(approvals.pull_request(7))
    assert len(queries) == 1
    assert [(what, method, path, can) for what, method, path, _text, can in texts] == [
        ("its body", "PATCH", "repos/{owner}/{repo}/pulls/7", True),
        (
            "the comment https://example.com/c11",
            "PATCH",
            "repos/{owner}/{repo}/issues/comments/11",
            True,
        ),
        (
            "the review https://example.com/v31",
            "PUT",
            "repos/{owner}/{repo}/pulls/7/reviews/31",
            True,
        ),
        (
            "the comment https://example.com/r21",
            "PATCH",
            "repos/{owner}/{repo}/pulls/comments/21",
            True,
        ),
    ]
